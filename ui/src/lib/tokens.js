/** Hex to 0xRRGGBB for three.js. */
export const hex = c => parseInt(String(c).slice(1, 7), 16);
/** Hex plus alpha to an rgba() string, for canvas and SVG fills. */
export const rgba = (c, a) => {
  const n = hex(c);
  return `rgba(${(n >> 16) & 255},${(n >> 8) & 255},${n & 255},${a})`;
};
